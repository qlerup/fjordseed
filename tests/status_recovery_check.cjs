const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../static/app.js'),'utf8');
const context=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function preserveTorrentSnapshot('),source.indexOf('function renderFlow(')),context);
const previous={id:'seed',profile_id:'gateway',torrents:[{hash:'a',progress:.26}]};
const unavailable={id:'seed',profile_id:'gateway',ready:false,torrents_available:false,torrents:[],message:'Afventer forbindelse.'};
const stale=context.preserveTorrentSnapshot(unavailable,previous);
assert.equal(stale.torrents,previous.torrents);
assert.equal(stale.ready,false);
assert.match(stale.message,/ikke live/);
assert.equal(context.preserveTorrentSnapshot({...unavailable,profile_id:'old-vpn'},previous).torrents.length,0);
assert.equal(context.preserveTorrentSnapshot({...unavailable,id:'other-seed'},previous).torrents.length,0);
assert.equal(context.preserveTorrentSnapshot(unavailable,undefined).torrents.length,0);
const empty={...unavailable,torrents_available:true,ready:true};
assert.equal(context.preserveTorrentSnapshot(empty,stale),empty);
const recovered={...empty,torrents:[{hash:'a',progress:.8}]};
assert.equal(context.preserveTorrentSnapshot(recovered,stale),recovered);
console.log('PASS unavailable status preserves torrents, recovery replaces snapshot, profiles remain isolated');
